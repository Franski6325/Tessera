def for_roles(roles: list[RoleId] | tuple[RoleId, ...]) -> tuple[Pkg, ...]:
    wanted = set(roles)
    if not wanted:
        return tuple()
    return tuple(p for p in PACKAGES if wanted.intersection(p.roles))


def by_id(pid: str) -> Pkg | None:
    for p in PACKAGES:
        if p.id == pid:
            return p
    return None


def name_for(pkg: Pkg, family: DistroFamily) -> str | None:
    return pkg.names.get(family) or pkg.names.get(DistroFamily.UNKNOWN)
