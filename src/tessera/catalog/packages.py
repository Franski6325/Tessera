"""Role-scoped tools. Names mapped per family. Missing names are skipped, never invented as installs."""

from __future__ import annotations

from dataclasses import dataclass

from tessera.models import DistroFamily, RoleId

Family = DistroFamily


@dataclass(frozen=True)
class Pkg:
    id: str
    roles: tuple[RoleId, ...]
    summary_it: str
    summary_en: str
    names: dict[DistroFamily, str | None]
    aur: str | None = None
    flatpak: str | None = None
    pipx: str | None = None
    kali_only: bool = False
    blackarch: str | None = None
    recommended: bool = True
    heavy: bool = False  # skip on < 8 GiB unless forced
    legal: str = "lab"  # lab = authorized testing / daily = everyday


def n(
    default: str | None = None,
    *,
    debian: str | None = None,
    ubuntu: str | None = None,
    kali: str | None = None,
    arch: str | None = None,
    fedora: str | None = None,
    rhel: str | None = None,
    suse: str | None = None,
    alpine: str | None = None,
    void: str | None = None,
    gentoo: str | None = None,
    nixos: str | None = None,
) -> dict[DistroFamily, str | None]:
    """Fill every family. Explicit None means 'not packaged here'."""
    deb = debian if debian is not None else default
    ubu = ubuntu if ubuntu is not None else deb
    kal = kali if kali is not None else ubu
    fed = fedora if fedora is not None else default
    return {
        DistroFamily.DEBIAN: deb,
        DistroFamily.UBUNTU: ubu,
        DistroFamily.KALI: kal,
        DistroFamily.ARCH: arch if arch is not None else default,
        DistroFamily.FEDORA: fed,
        DistroFamily.RHEL: rhel if rhel is not None else fed,
        DistroFamily.SUSE: suse if suse is not None else default,
        DistroFamily.ALPINE: alpine if alpine is not None else default,
        DistroFamily.VOID: void if void is not None else default,
        DistroFamily.GENTOO: gentoo if gentoo is not None else default,
        DistroFamily.NIXOS: nixos if nixos is not None else default,
        DistroFamily.UNKNOWN: default,
    }


